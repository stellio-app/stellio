"""1.1.7 — archive G-code : compression, empreinte, plafond, isolation, invités refusés, téléchargement identique."""
import gzip, hashlib, importlib.util, io, logging, os, sqlite3
import pytest
flask = pytest.importorskip('flask')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _env(tmp_path, role='user'):
    spec = importlib.util.spec_from_file_location('print_gcode_archive_t', os.path.join(ROOT, 'modules', 'print_gcode_archive.py'))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    db = str(tmp_path / 'g.db')
    def get_db():
        c = sqlite3.connect(db); c.row_factory = sqlite3.Row; return c
    src = tmp_path / 'src'; src.mkdir()
    (src / 'pièce.gcode').write_bytes(b'G1 X1 Y1\n' * 5000)
    (src / 'modele.stl').write_bytes(b'solid')
    c = get_db()
    c.execute("CREATE TABLE print_history (id INTEGER PRIMARY KEY, user_id INT, file_path TEXT, file_name TEXT)")
    c.execute("INSERT INTO print_history VALUES (1, 1, ?, 'pièce.gcode')", (str(src / 'pièce.gcode'),))
    c.execute("INSERT INTO print_history VALUES (2, 1, ?, 'modele.stl')", (str(src / 'modele.stl'),))
    c.execute("INSERT INTO print_history VALUES (3, 2, ?, 'pièce.gcode')", (str(src / 'pièce.gcode'),))
    c.commit(); c.close()
    app = flask.Flask('g'); app.secret_key = 'k'
    data = tmp_path / 'data'; data.mkdir()
    m.init(dict(DATA_DIR=str(data), _is_path_within_sources=lambda p, uid: str(p).startswith(str(src)), app=app, app_logger=logging.getLogger('t'),
                get_db=get_db, jsonify=flask.jsonify, login_required=lambda f: f, request=flask.request, session=flask.session, Response=flask.Response))
    cl = app.test_client()
    with cl.session_transaction() as s: s['user_id'] = 1; s['role'] = role
    return m, cl, data


def test_archive_depuis_l_entree_telechargement_identique(tmp_path):
    m, cl, data = _env(tmp_path)
    assert cl.get('/api/print-history/1/gcode').get_json()['archived'] is False
    r = cl.post('/api/print-history/1/gcode'); j = r.get_json()
    raw = b'G1 X1 Y1\n' * 5000
    assert r.status_code == 201 and j['raw_size'] == len(raw) and j['sha256'] == hashlib.sha256(raw).hexdigest() and j['gz_size'] < len(raw) // 5
    d = cl.get('/api/print-history/1/gcode/download')
    assert d.status_code == 200 and d.data == raw and 'attachment' in d.headers['Content-Disposition']
    assert cl.get('/api/print-history/1/gcode').get_json()['archive']['sha256'] == j['sha256']
    assert cl.delete('/api/print-history/1/gcode').get_json()['ok'] and cl.get('/api/print-history/1/gcode/download').status_code == 404
    assert cl.delete('/api/print-history/1/gcode').status_code == 404 and not os.listdir(data / 'gcode_archive')


def test_envoi_de_fichier_validations_et_plafond(tmp_path, monkeypatch):
    m, cl, data = _env(tmp_path)
    assert cl.post('/api/print-history/2/gcode').status_code == 400                                   # entrée STL : rien à archiver
    assert cl.post('/api/print-history/9/gcode').status_code == 404 and cl.post('/api/print-history/3/gcode').status_code == 404   # inconnue / autre compte
    bad = cl.post('/api/print-history/2/gcode', data={'file': (io.BytesIO(b'x'), 'virus.exe')}, content_type='multipart/form-data')
    assert bad.status_code == 400
    ok = cl.post('/api/print-history/2/gcode', data={'file': (io.BytesIO(b'M104 S200\n'), '../../etc/x.gcode')}, content_type='multipart/form-data')
    assert ok.status_code == 201 and ok.get_json()['name'] == 'x.gcode'                               # nom nettoyé, pas de traversée
    monkeypatch.setattr(m, 'MAX_RAW', 100)
    big = io.BytesIO(b'a' * 500)
    with pytest.raises(ValueError):
        m.compress(big, str(tmp_path / 'z.gz'), limit=100)
    assert not (tmp_path / 'z.gz').exists()                                                           # fichier partiel supprimé


def test_invite_et_demo_refuses(tmp_path):
    m, cl, data = _env(tmp_path, role='viewer')
    for method, url in (('post', '/api/print-history/1/gcode'), ('get', '/api/print-history/1/gcode'), ('get', '/api/print-history/1/gcode/download'), ('delete', '/api/print-history/1/gcode')):
        assert getattr(cl, method)(url).status_code == 403, url


def _gcode_archive_mod():
    spec = importlib.util.spec_from_file_location('gcode_archive_t', os.path.join(ROOT, 'modules', 'gcode_archive.py'))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m


def test_gcode_joint_poids_et_duree_reels_selon_le_slicer(tmp_path):
    m = _gcode_archive_mod()
    cas = {
        'prusa': ('; generated by PrusaSlicer 2.7\n; filament used [g] = 12.30, 4.50\n; estimated printing time (normal mode) = 1d 2h 3m 4s\n; filament_type = PLA\n', 16.8, 86400 + 7200 + 180 + 4),
        'orca': ('; generated by OrcaSlicer\n; filament used [g] = 5.64\n; estimated printing time (normal mode) = 2h 03m 10s\n', 5.64, 7390),
        'bambu': ('; BambuStudio\n; total filament weight [g] : 7.25\n; total estimated time: 1h 2m 3s\n', 7.25, 3723),
        'cura': (';FLAVOR:Marlin\n;TIME:5400\n', 0, 5400),
    }
    for nom, (txt, w, s) in cas.items():
        f = tmp_path / (nom + '.gcode'); f.write_text(txt)
        meta = m._extract_gcode_meta(str(f))
        assert meta.get('weight_g', 0) == w and meta.get('time_s', 0) == s, (nom, meta)
    assert m._to_seconds('2h 03m') == 7380 and m._to_seconds('3723') == 3723 and m._to_seconds('n/a') == 0 and m._to_grams('1.5, x, 2') == 3.5


def test_estimation_depuis_le_gcode_joint_isolee_par_compte(tmp_path):
    m = _gcode_archive_mod()
    db = str(tmp_path / 'g.db')
    def get_db():
        c = sqlite3.connect(db); c.row_factory = sqlite3.Row; return c
    m.get_db = get_db
    c = get_db()
    c.execute("CREATE TABLE project_gcodes (id INTEGER PRIMARY KEY, project_id INT, user_id INT, name TEXT, meta TEXT, file_path TEXT, created_at TEXT DEFAULT '')")
    c.execute("INSERT INTO project_gcodes (user_id, name, meta, file_path, created_at) VALUES (1, 'sans.gcode', '{\"time\": \"1h 00m\"}', '/m/a.stl', '1')")        # pas de poids : ignoré
    c.execute("INSERT INTO project_gcodes (user_id, name, meta, file_path, created_at) VALUES (1, 'ancien.gcode', '{\"weight\": \"10.5\", \"time\": \"2h 30m\"}', '/m/a.stl', '2')")   # ancien format : texte seulement
    c.execute("INSERT INTO project_gcodes (user_id, name, meta, file_path, created_at) VALUES (2, 'autre.gcode', '{\"weight_g\": 99, \"time_s\": 99}', '/m/a.stl', '3')")
    c.commit(); c.close()
    e = m.gcode_estimate_for('/m/a.stl', 1)
    assert e['name'] == 'ancien.gcode' and e['weight_g'] == 10.5 and e['time_seconds'] == 9000
    assert m.gcode_estimate_for('/m/a.stl', 3) is None and m.gcode_estimate_for('/m/b.stl', 1) is None


