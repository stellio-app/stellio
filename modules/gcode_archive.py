GCODE_ARCHIVE_EXTS = ('.gcode', '.gco', '.gc', '.bgcode')

GCODE_ARCHIVE_MAX_BYTES = 1024 * 1024 * 1024

_GCODE_META_KEYS = {
    'filament_type': 'material', 'filament_settings_id': 'filament', 'nozzle_diameter': 'nozzle',
    'layer_height': 'layer', 'nozzle_temperature': 'temp', 'temperature': 'temp', 'bed_temperature': 'bed',
    'hot_plate_temp': 'bed', 'first_layer_bed_temperature': 'bed', 'filament used [g]': 'weight',
    'total filament weight [g]': 'weight', 'filament used [mm]': 'length', 'estimated printing time (normal mode)': 'time',
    'total estimated time': 'time', 'print_settings_id': 'profile', 'printer_settings_id': 'printer',
    'fill_density': 'infill', 'sparse_infill_density': 'infill', 'perimeters': 'walls', 'wall_loops': 'walls',
}

def _extract_gcode_meta(path):
    """Réglages lus dans les commentaires du G-code (PrusaSlicer, OrcaSlicer, Bambu Studio, Cura) : matière, buse, hauteur de couche,
    températures, durée, poids. Ne lit que le début et la fin du fichier."""
    meta = {}
    try:
        size = os.path.getsize(path)
        chunks = []
        with open(path, 'rb') as f:
            chunks.append(f.read(96 * 1024))
            if size > 96 * 1024:
                f.seek(max(96 * 1024, size - 192 * 1024))
                chunks.append(f.read())
        text = b'\n'.join(chunks).decode('utf-8', errors='ignore')
    except Exception:
        return meta
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith(';'):
            continue
        body = line.lstrip(';').strip()
        low = body.lower()
        if low.startswith('generated by') or low.startswith('flavor:'):
            meta.setdefault('slicer', body.split(':', 1)[-1].strip()[:80] if low.startswith('flavor:') else body[12:].strip()[:80])
            continue
        if low.startswith('time:'):
            try:
                sec = int(float(body.split(':', 1)[1]))
                meta.setdefault('time', f"{sec // 3600}h {(sec % 3600) // 60:02d}m")
                meta.setdefault('time_s', sec)
            except Exception:
                pass
            continue
        if '=' in body:
            key, _, val = body.partition('=')
        elif ':' in body:                                  # Bambu Studio : « total filament weight [g] : 5.64 »
            key, _, val = body.partition(':')
            if key.strip().lower() not in _GCODE_META_KEYS:
                continue
        else:
            continue
        k = _GCODE_META_KEYS.get(key.strip().lower())
        if not k or k in meta:
            continue
        raw = val.strip().split(';')[0].strip().strip('"')
        v = raw.split(',')[0].strip().strip('"')
        if v:
            meta[k] = v[:80]
            if k == 'weight':
                meta['weight_g'] = _to_grams(raw)          # tous les filaments du travail (multicolore), pas seulement le premier
            elif k == 'time':
                meta['time_s'] = _to_seconds(raw)
    return meta


def _to_seconds(v):
    """« 1d 2h 3m 4s », « 2h 03m », « 3723 » ou 3723 → secondes (0 si illisible)."""
    s = str(v or '').strip().lower()
    if not s:
        return 0
    try:
        return int(float(s))
    except ValueError:
        pass
    total, found = 0, False
    for num, unit in re.findall(r'(\d+(?:\.\d+)?)\s*([dhms])', s):
        found = True
        total += float(num) * {'d': 86400, 'h': 3600, 'm': 60, 's': 1}[unit]
    return int(total) if found else 0


def _to_grams(v):
    """« 12.3 » ou « 12.3, 4.5 » → total en grammes (0 si illisible)."""
    total = 0.0
    for part in re.split(r'[,;]', str(v or '')):
        try:
            total += float(part.strip().strip('"'))
        except ValueError:
            pass
    return round(total, 2)


def gcode_estimate_for(file_path, user_id):
    """Poids et durée réels d'un fichier d'après le G-code qui lui est joint (le plus récent qui les contient), ou None.
    C'est le tranchage réel : plus proche de la vérité qu'une estimation du slicer ou de la géométrie."""
    conn = get_db()
    try:
        rows = conn.execute(
            "SELECT id, name, meta FROM project_gcodes WHERE user_id = ? AND file_path = ? ORDER BY created_at DESC, id DESC",
            (user_id, file_path)).fetchall()
    finally:
        conn.close()
    for r in rows:
        try:
            m = json.loads(r['meta'] or '{}')
        except Exception:
            m = {}
        w = float(m.get('weight_g') or 0) or _to_grams(m.get('weight'))     # anciens enregistrements : seulement le texte
        s = int(m.get('time_s') or 0) or _to_seconds(m.get('time'))
        if w > 0 and s > 0:
            return {'id': r['id'], 'name': r['name'], 'weight_g': w, 'time_seconds': s, 'material': m.get('material', ''),
                    'nozzle': m.get('nozzle', ''), 'layer': m.get('layer', ''), 'slicer': m.get('slicer', '')}
    return None

