"""Stellio — historique d'impression enrichi (1.1.7) : températures réelles et version du slicer.

Les valeurs sont lues dans l'en-tête et le pied du G-code (PrusaSlicer, OrcaSlicer, Bambu Studio, Cura, Simplify3D), à défaut dans les
premières commandes M104/M109 (buse) et M140/M190 (plateau). Colonnes ajoutées par la migration 2 (migrations.py).
Rien n'est inventé : sans information fiable, la valeur reste vide.
"""
import os
import re

_REQUIRED = (
    '_is_path_within_sources',
    'app',
    'app_logger',
    'get_db',
    'jsonify',
    'login_required',
    'request',
    'session',
)
_OPTIONAL = ()
_OVERRIDABLE = ('os',)

_MAIN = {}
_is_path_within_sources = None
app = None
app_logger = None
get_db = None
jsonify = None
login_required = None
request = None
session = None

HEAD_BYTES = 256 * 1024
TAIL_BYTES = 128 * 1024
BULK_MAX = 200

_SLICERS = (
    ('PrusaSlicer', re.compile(r'generated by PrusaSlicer\s+([\w.\-+]+)', re.I)),
    ('SuperSlicer', re.compile(r'generated by SuperSlicer\s+([\w.\-+]+)', re.I)),
    ('OrcaSlicer', re.compile(r'generated by OrcaSlicer\s+([\w.\-+]+)', re.I)),
    ('BambuStudio', re.compile(r'^;\s*BambuStudio\s+([\w.\-+]+)', re.I | re.M)),
    ('Cura', re.compile(r'Generated with Cura_SteamEngine\s+([\w.\-+]+)', re.I)),
    ('Simplify3D', re.compile(r'generated by Simplify3D\(R\)\s+Version\s+([\w.\-+]+)', re.I)),
    ('Slic3r', re.compile(r'generated by Slic3r\s+([\w.\-+]+)', re.I)),
)
_NOZZLE_KEYS = (r'^;\s*(?:nozzle_temperature|temperature)\s*=\s*(\d+)', r'^;\s*EXTRUDER_TRAIN\.0\.INITIAL_TEMPERATURE:(\d+)',
                r'^;\s*first_layer_temperature\s*=\s*(\d+)')
_BED_KEYS = (r'^;\s*(?:bed_temperature|hot_plate_temp|first_layer_bed_temperature)\s*=\s*(\d+)', r'^;\s*BUILD_PLATE\.INITIAL_TEMPERATURE:(\d+)')
_M_NOZZLE = re.compile(r'^M10[49]\s+[^\n;]*?S(\d+(?:\.\d+)?)', re.M)
_M_BED = re.compile(r'^M1(?:40|90)\s+[^\n;]*?S(\d+(?:\.\d+)?)', re.M)


def _first_int(patterns, text, lo=1, hi=500):
    for p in patterns:
        for m in re.finditer(p, text, re.M | re.I):
            v = int(m.group(1))
            if lo <= v <= hi:
                return float(v)
    return None


def _first_cmd(rx, text, lo=1, hi=500):
    for m in rx.finditer(text):
        v = float(m.group(1))
        if lo <= v <= hi:
            return v
    return None


def parse_gcode(text):
    """{'slicer', 'slicer_version', 'nozzle_temp', 'bed_temp'} — valeurs absentes = None."""
    slicer = version = None
    for name, rx in _SLICERS:
        m = rx.search(text)
        if m:
            slicer, version = name, m.group(1)
            break
    nozzle = _first_int(_NOZZLE_KEYS, text, 150, 500) or _first_cmd(_M_NOZZLE, text, 150, 500)
    bed = _first_int(_BED_KEYS, text, 20, 200) or _first_cmd(_M_BED, text, 20, 200)
    return {'slicer': slicer, 'slicer_version': version, 'nozzle_temp': nozzle, 'bed_temp': bed}


def read_gcode_text(path, opener=open):
    with opener(path, 'rb') as f:
        f.seek(0, 2)
        size = f.tell()
        f.seek(0)
        head = f.read(HEAD_BYTES)
        tail = b''
        if size > HEAD_BYTES:
            f.seek(max(HEAD_BYTES, size - TAIL_BYTES))
            tail = f.read(TAIL_BYTES)
    return (head + b'\n' + tail).decode('utf-8', 'replace')


def _has_cols(conn):
    cols = {r[1] for r in conn.execute("PRAGMA table_info(print_history)").fetchall()}
    return {'nozzle_temp', 'bed_temp', 'slicer_version'} <= cols


def enrich_row(conn, uid, hid, text=None):
    """Complète une ligne d'historique depuis son G-code. Retourne les valeurs trouvées ou None."""
    row = conn.execute("SELECT id, file_path, file_ext, nozzle_temp, bed_temp, slicer_version FROM print_history WHERE id=? AND user_id=?", (hid, uid)).fetchone()
    if not row:
        return None
    if text is None:
        p = row['file_path'] or ''
        if os.path.splitext(p)[1].lower() not in ('.gcode', '.gco', '.gc') or not _is_path_within_sources(p, uid) or not os.path.isfile(p):
            return {}
        text = read_gcode_text(p)
    found = {k: v for k, v in parse_gcode(text).items() if v is not None and k != 'slicer'}
    sets, args = [], []
    for col in ('nozzle_temp', 'bed_temp', 'slicer_version'):
        if col in found and not row[col]:
            sets.append(f"{col} = ?")
            args.append(found[col])
    if sets:
        conn.execute(f"UPDATE print_history SET {', '.join(sets)} WHERE id = ? AND user_id = ?", args + [hid, uid])
        conn.commit()
    return found


def _no_viewer():
    if session.get('role') == 'viewer':
        return jsonify({'error': 'Réservé au compte propriétaire.', 'code': 'viewer_forbidden'}), 403
    return None


def api_history_enrich(hid):
    r = _no_viewer()
    if r:
        return r
    conn = get_db()
    try:
        if not _has_cols(conn):
            return jsonify({'error': 'Base non migrée (redémarrez Stellio).'}), 409
        found = enrich_row(conn, session['user_id'], hid)
        if found is None:
            return jsonify({'error': 'Impression introuvable.'}), 404
        return jsonify({'ok': True, 'found': found})
    finally:
        conn.close()


def api_history_enrich_all():
    r = _no_viewer()
    if r:
        return r
    conn = get_db()
    try:
        if not _has_cols(conn):
            return jsonify({'error': 'Base non migrée (redémarrez Stellio).'}), 409
        ids = [x[0] for x in conn.execute(
            "SELECT id FROM print_history WHERE user_id=? AND (nozzle_temp IS NULL OR bed_temp IS NULL OR COALESCE(slicer_version,'')='') "
            "AND lower(file_ext) IN ('.gcode','gcode','.gco','.gc') ORDER BY id DESC LIMIT ?", (session['user_id'], BULK_MAX)).fetchall()]
        done = 0
        for hid in ids:
            try:
                if enrich_row(conn, session['user_id'], hid):
                    done += 1
            except Exception as e:
                app_logger.debug(f"[ENRICH] {hid}: {type(e).__name__}")
        return jsonify({'ok': True, 'checked': len(ids), 'completed': done})
    finally:
        conn.close()


def api_history_details_set(hid):
    r = _no_viewer()
    if r:
        return r
    data = request.get_json(silent=True) or {}
    sets, args = [], []
    for col, lo, hi in (('nozzle_temp', 0, 500), ('bed_temp', 0, 200)):
        if col in data:
            try:
                v = None if data[col] in (None, '') else float(data[col])
            except (TypeError, ValueError):
                return jsonify({'error': f'{col} invalide.'}), 400
            if v is not None and not (lo <= v <= hi):
                return jsonify({'error': f'{col} hors limites.'}), 400
            sets.append(f"{col} = ?")
            args.append(v)
    if 'slicer_version' in data:
        sets.append("slicer_version = ?")
        args.append(str(data['slicer_version'] or '')[:40])
    if not sets:
        return jsonify({'error': 'Rien à modifier.'}), 400
    conn = get_db()
    try:
        if not _has_cols(conn):
            return jsonify({'error': 'Base non migrée (redémarrez Stellio).'}), 409
        cur = conn.execute(f"UPDATE print_history SET {', '.join(sets)} WHERE id = ? AND user_id = ?", args + [hid, session['user_id']])
        conn.commit()
        if not cur.rowcount:
            return jsonify({'error': 'Impression introuvable.'}), 404
        return jsonify({'ok': True})
    finally:
        conn.close()


_ROUTES = (
    ('/api/history/<int:hid>/enrich', ['POST'], 'api_history_enrich', ('login_required', )),
    ('/api/history/enrich-all', ['POST'], 'api_history_enrich_all', ('login_required', )),
    ('/api/history/<int:hid>/details', ['PUT'], 'api_history_details_set', ('login_required', )),
)


def init(ns, routes=True):
    """Reçoit les services de main.py (dict des globals) et enregistre les routes Flask."""
    g = globals()
    g['_MAIN'] = ns
    missing = [n for n in _REQUIRED if n not in ns]
    if missing:
        raise RuntimeError(f"{__name__}.init : services manquants : {missing}")
    for n in _REQUIRED + _OPTIONAL + _OVERRIDABLE:
        if n in ns:
            g[n] = ns[n]
    if routes:
        for rule, methods, fname, decos in _ROUTES:
            view = g[fname]
            for d in reversed(decos):
                view = eval(d, g)(view)
            g['app'].add_url_rule(rule, endpoint=fname, view_func=view, methods=methods)
    return {}
